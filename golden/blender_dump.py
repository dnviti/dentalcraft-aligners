"""Tier B of the golden harness: what only Blender can produce.

    blender -b --factory-startup -P golden/blender_dump.py -- --out golden/fixtures

For each of the six demo scans (UPPER / LOWER x MILD / MODERATE / SEVERE) it
  * generates the synthetic arch with the plugin's `demo.generate` (voxel remesh
    0.35 mm, seed 7, the ground-truth tooth label of every vertex),
  * computes the arch frame from the ground-truth seeds (`oracle.frame`),
  * decimates the scan in arch coordinates with Blender's Decimate modifier, the
    function `case_teeth._decimate_here` that segmentation consumes
    (`rw_faces` = 30000 faces),
and writes to `<out>/<case>/`:
    scan.dcm       full scan, world coordinates, ground-truth FDI per vertex (u16)
    decimated.dcm  decimated scan, arch coordinates (input of segmentation)
    meta.json      arch, severity, seed, voxel, ground-truth seeds and malposition,
                   arch frame, provenance
The plugin is loaded from its read-only repository by path (nothing installed in
Blender's config, no bytecode written there).  Run with `--factory-startup`.
"""
import argparse
import os
import subprocess
import sys

sys.dont_write_bytecode = True
os.environ.setdefault("PYTHONDONTWRITEBYTECODE", "1")
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
import numpy as np  # noqa: E402

from oracle import frame, mesh, plugin  # noqa: E402

CASES = [(arch, sev) for arch in ("UPPER", "LOWER") for sev in ("MILD", "MODERATE", "SEVERE")]


def parse_args():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser(prog="blender_dump.py")
    ap.add_argument("--out", default=os.path.join(HERE, "fixtures"))
    ap.add_argument("--plugin", default=plugin.PLUGIN_ROOT, help="root of the (read-only) plugin repository")
    ap.add_argument("--voxel", type=float, default=0.35)
    ap.add_argument("--seed", type=int, default=7)
    ap.add_argument("--faces", type=int, default=None, help="decimation target (default: evidence rw_faces)")
    ap.add_argument("--only", default="", help="comma list of cases, e.g. lower_mild,upper_severe")
    return ap.parse_args(argv)


def git_rev(root):
    try:
        return subprocess.check_output(["git", "-C", root, "rev-parse", "HEAD"], text=True,
                                       stderr=subprocess.DEVNULL).strip()
    except Exception:
        return None


def decimate_function(mu):
    """`case_teeth._decimate_here` (needs bpy, so the module is not imported: only that function)."""
    ns = {"bpy": bpy, "mu": mu, "np": np}
    plugin.extract("case_teeth", ["_decimate_here"], ns)
    return ns["_decimate_here"]


def clear_objects():
    for o in list(bpy.data.objects):
        bpy.data.objects.remove(o, do_unlink=True)
    for m in list(bpy.data.meshes):
        bpy.data.meshes.remove(m)


def dump_case(arch, sev, args, demo, mu, dec, faces, out):
    name = f"demo_{arch.lower()}_{sev.lower()}"
    d = os.path.join(out, name)
    os.makedirs(d, exist_ok=True)
    obj, seeds, info = demo.generate(bpy, arch, sev, seed=args.seed, voxel=args.voxel)
    V = mu.get_verts(obj.data)
    T = mu.get_tris(obj.data)
    gt = np.zeros(len(V), np.int32)
    obj.data.attributes["oa_gt_label"].data.foreach_get("value", gt)
    seeds = {int(f): np.asarray(p, np.float64) for f, p in seeds.items()}
    M = frame.compute_frame(seeds, V)
    Vd_in = mu.transform_points(mu.rigid_inverse(M), V)           # case_teeth._arch_arrays (matrix_world = I)
    Vd, Td = dec(Vd_in, T, faces)
    mesh.write_dcm(os.path.join(d, "scan.dcm"), V, T, vertex_labels=gt)
    mesh.write_dcm(os.path.join(d, "decimated.dcm"), Vd, Td)
    meta = {
        "case": name, "arch": arch, "severity": sev, "seed": args.seed, "voxel_mm": args.voxel,
        "decimate_faces_target": faces, "n_vertices": int(len(V)), "n_faces": int(len(T)),
        "n_vertices_decimated": int(len(Vd)), "n_faces_decimated": int(len(Td)),
        "scan_coordinates": "world (as generated by demo.generate)",
        "decimated_coordinates": "arch frame M (case_teeth._arch_arrays), f32",
        "frame_gt": [[float(x) for x in r] for r in M],
        "seeds_gt_world": {str(f): [float(x) for x in p] for f, p in sorted(seeds.items())},
        "malposition_gt": {str(f): {k: float(v) for k, v in i.items() if k != "seed_point"}
                           for f, i in sorted(info.items())},
        "synthetic": "THE RESULT IS A SYNTHETIC MODEL, NOT PATIENT DATA",
        "provenance": {"blender": bpy.app.version_string, "plugin_rev": git_rev(args.plugin),
                       "numpy": np.__version__, "tier": "B"},
    }
    mesh.dump_json(os.path.join(d, "meta.json"), meta)
    bpy.data.objects.remove(obj, do_unlink=True)
    print(f"[golden] {name}: scan {len(V)}v/{len(T)}f, decimated {len(Vd)}v/{len(Td)}f")


def main():
    args = parse_args()
    plugin.PLUGIN_ROOT = args.plugin
    plugin.install(args.plugin)
    demo, mu, ev = plugin.load("demo"), plugin.load("meshutil"), plugin.load("evidence")
    faces = args.faces or int(ev.P["rw_faces"].value)
    dec = decimate_function(mu)
    only = {s for s in args.only.split(",") if s}
    clear_objects()
    done = 0
    for arch, sev in CASES:
        if only and f"{arch.lower()}_{sev.lower()}" not in only:
            continue
        dump_case(arch, sev, args, demo, mu, dec, faces, args.out)
        done += 1
    print(f"[golden] Tier B: {done} case(s) written to {args.out}")


if __name__ == "__main__":
    main()
