    fn placeholders(s: &str) -> BTreeSet<String> {
        s.split('{')
            .skip(1)
            .filter_map(|p| p.split('}').next())
            .map(str::to_owned)
            .collect()
    }

    #[test]
    fn every_entry_has_both_languages_with_the_same_placeholders() {
        let mut keys = BTreeSet::new();
        for (k, en, it) in TABLE {
            assert!(keys.insert(*k), "duplicate key {k}");
            assert!(!en.is_empty() && !it.is_empty(), "{k}");
            assert_eq!(placeholders(en), placeholders(it), "{k}");
            assert!(
                k.starts_with("chk-") || k.starts_with("rpt-") || k.starts_with("pat-"),
                "{k}"
            );
        }
    }

    #[test]
    fn arguments_are_inserted_and_unknown_keys_come_back() {
        assert_eq!(fmt(Lang::En, "chk-boundary", &["3".into()]), "3 open edges");
        assert_eq!(
            fmt(Lang::It, "chk-boundary", &["3".into()]),
            "3 spigoli aperti"
        );
        assert_eq!(tr(Lang::En, "nope"), "nope");
    }

    /// Every key used in the sources of this module is in the table.
    #[test]
    fn every_key_the_code_uses_exists() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src/export");
        let known: BTreeSet<&str> = TABLE.iter().map(|(k, _, _)| *k).collect();
        for file in ["report.rs", "patient.rs", "printcheck.rs"] {
            let src = std::fs::read_to_string(dir.join(file)).unwrap();
            for part in src.split('"').skip(1).step_by(2) {
                let key = part.trim_start_matches('<');
                let looks_like_key = ["rpt-", "pat-", "chk-"].iter().any(|p| key.starts_with(p))
                    && key
                        .chars()
                        .all(|c| c.is_ascii_lowercase() || c == '-' || c.is_ascii_digit());
                if looks_like_key {
                    assert!(known.contains(key), "{file}: unknown key {key}");
                }
            }
        }
    }
